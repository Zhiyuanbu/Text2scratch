create or replace function public.resolve_login_email(login_identifier text)
returns text
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  normalized_identifier text := lower(trim(coalesce(login_identifier, '')));
  resolved_email text;
begin
  if normalized_identifier = '' then
    return null;
  end if;

  if position('@' in normalized_identifier) > 0 then
    return normalized_identifier;
  end if;

  select lower(coalesce(p.email, u.email))
  into resolved_email
  from auth.users u
  left join public.profiles p on p.id = u.id
  where lower(coalesce(p.username, u.raw_user_meta_data ->> 'username', '')) = normalized_identifier
  limit 1;

  return resolved_email;
end;
$$;

create or replace function public.delete_current_account()
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  if auth.uid() is null then
    raise exception 'Not signed in.' using errcode = '42501';
  end if;

  delete from auth.users where id = auth.uid();
end;
$$;

create or replace function public.public_project_registry(limit_rows integer default 200)
returns table (
  id uuid,
  title text,
  share_slug text,
  owner_username text,
  updated_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select p.id, p.title, p.share_slug, p.owner_username, p.updated_at
  from public.projects p
  where p.is_public = true
    and p.share_slug is not null
  order by p.updated_at desc
  limit greatest(1, least(coalesce(limit_rows, 200), 500));
$$;

create or replace function public.admin_list_projects(max_rows integer default 100)
returns table (
  id uuid,
  title text,
  owner_username text,
  is_public boolean,
  updated_at timestamptz
)
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  if not public.is_admin_user() then
    raise exception 'Admin privileges required.' using errcode = '42501';
  end if;

  return query
  select p.id, p.title, p.owner_username, p.is_public, p.updated_at
  from public.projects p
  order by p.updated_at desc
  limit greatest(1, least(coalesce(max_rows, 100), 500));
end;
$$;

create or replace function public.admin_restrict_account(identifier text)
returns uuid
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  normalized_identifier text := lower(trim(coalesce(identifier, '')));
  target_user_id uuid;
  target_email text;
  target_username text;
begin
  if not public.is_admin_user() then
    raise exception 'Admin privileges required.' using errcode = '42501';
  end if;

  if normalized_identifier = '' then
    raise exception 'Identifier is required.';
  end if;

  select u.id,
         coalesce(p.email, u.email),
         coalesce(p.username, public.normalize_username(u.raw_user_meta_data ->> 'username'))
  into target_user_id, target_email, target_username
  from auth.users u
  left join public.profiles p on p.id = u.id
  where lower(coalesce(p.email, u.email, '')) = normalized_identifier
     or lower(coalesce(p.username, u.raw_user_meta_data ->> 'username', '')) = normalized_identifier
  limit 1;

  if target_user_id is null then
    raise exception 'User not found.';
  end if;

  insert into public.profiles (id, username, email, is_banned, banned_reason, banned_at)
  values (
    target_user_id,
    coalesce(target_username, 'user_' || left(replace(target_user_id::text, '-', ''), 8)),
    coalesce(target_email, ''),
    true,
    'Restricted by admin',
    now()
  )
  on conflict (id) do update
    set is_banned = true,
        banned_reason = 'Restricted by admin',
        banned_at = now(),
        updated_at = now();

  update public.projects
  set is_public = false,
      share_slug = null,
      updated_at = now()
  where owner_id = target_user_id;

  insert into public.account_bans (user_id, username, email, reason, created_by)
  values (target_user_id, target_username, target_email, 'Restricted by admin', auth.uid());

  return target_user_id;
end;
$$;

create or replace function public.admin_network_ban(ip_address text)
returns text
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  normalized_ip text := trim(coalesce(ip_address, ''));
begin
  if not public.is_admin_user() then
    raise exception 'Admin privileges required.' using errcode = '42501';
  end if;

  if normalized_ip = '' then
    raise exception 'IP address or CIDR is required.';
  end if;

  insert into public.network_bans (ip_address, reason, created_by)
  values (normalized_ip, 'Blocked by admin', auth.uid())
  on conflict (ip_address) do update
    set reason = excluded.reason,
        created_by = excluded.created_by,
        created_at = now();

  return normalized_ip;
end;
$$;

