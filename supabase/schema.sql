returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select
    length(public.normalize_username(candidate_username)) between 3 and 32
    and not exists (
      select 1
      from public.profiles
      where lower(username) = lower(public.normalize_username(candidate_username))
    );
$$;

