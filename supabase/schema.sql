create or replace function public.resolve_login_email(login_identifier text)
returns text
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  normalized_identifier text := lower(trim(coalesce(login_identifier, '')));
  resolved_email text;
begin
  if normalized_identifier = '' then
    return null;
  end if;

  if position('@' in normalized_identifier) > 0 then
    return normalized_identifier;
  end if;

  select lower(coalesce(p.email, u.email))
  into resolved_email
  from auth.users u
  left join public.profiles p on p.id = u.id
  where lower(coalesce(p.username, u.raw_user_meta_data ->> 'username', '')) = normalized_identifier
  limit 1;

  return resolved_email;
end;
$$;

