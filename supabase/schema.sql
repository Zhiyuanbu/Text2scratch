create or replace function public.handle_auth_user_profile()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  base_username text;
  next_username text;
begin
  base_username := public.normalize_username(
    coalesce(
      new.raw_user_meta_data ->> 'username',
      split_part(coalesce(new.email, ''), '@', 1),
      'user'
    )
  );

  if length(base_username) < 3 then
    base_username := 'user_' || left(replace(new.id::text, '-', ''), 8);
  end if;

  next_username := base_username;

  if exists (
    select 1
    from public.profiles
    where id <> new.id
      and lower(username) = lower(next_username)
  ) then
    next_username := left(base_username, 24) || '_' || left(replace(new.id::text, '-', ''), 6);
  end if;

  insert into public.profiles (id, username, email, last_sign_in_ip)
  values (new.id, next_username, coalesce(new.email, ''), public.get_client_ip())
  on conflict (id) do update
    set email = excluded.email,
        last_sign_in_ip = public.get_client_ip(),
        username = case
          when coalesce(public.profiles.username, '') = '' then excluded.username
          else public.profiles.username
        end,
        updated_at = now();

  return new;
end;
$$;

drop trigger if exists on_auth_user_profile_sync on auth.users;
create trigger on_auth_user_profile_sync
after insert or update of email, raw_user_meta_data on auth.users
for each row
execute function public.handle_auth_user_profile();

